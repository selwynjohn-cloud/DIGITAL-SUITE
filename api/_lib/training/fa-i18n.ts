export const FA_PUBLIC_URL = 'https://www.agilegroup-digital.co.in/training/fa';

export function isFaLang(v: unknown): v is Lang {
  return FA_LANGS.includes(String(v || '') as Lang);
}

export function faCopy(lang: string): Copy {
  const code = isFaLang(lang) ? lang : 'en';
  const base = copies.en;
  const row = copies[code] || base;
  return {
    ...base,
    ...row,
    rules: (row.rules || []).map((r, i) => ({
      title: r.title || base.rules[i]?.title || '',
      body: r.body || base.rules[i]?.body || '',
      example: r.example || '',
      doInstead: r.doInstead || base.rules[i]?.doInstead || '',
    })),
    questions: (row.questions || []).map((q, i) => ({
      title: q.title || base.questions[i]?.title || '',
      help: q.help || base.questions[i]?.help || '',
      correct: q.correct || base.questions[i]?.correct || 'no',
    })),
    pledges: row.pledges?.length ? row.pledges : base.pledges,
    hdfcSite: row.hdfcSite || base.hdfcSite,
    agileBranch: row.agileBranch || base.agileBranch,
    printCert: row.printCert || base.printCert,
    certCode: row.certCode || base.certCode,
    locNeed: row.locNeed || base.locNeed,
    alreadyDone: row.alreadyDone || base.alreadyDone,
    listenAll: row.listenAll || base.listenAll,
    exampleWord: row.exampleWord || base.exampleWord,
    doRight: row.doRight || base.doRight,
    punishBanner: row.punishBanner || base.punishBanner,
    victimLine: row.victimLine || base.victimLine,
  };
}
