export type HdfcFormKey = (typeof HDFC_FORM_KEYS)[number]

export function emptyHdfcForm(): Record<string, string> {
  const out: Record<string, string> = {}
  for (const k of HDFC_FORM_KEYS) out[k] = ''
  return out
}

export function normalizeHdfcForm(raw: unknown): Record<string, string> {
  const src = raw && typeof raw === 'object' ? (raw as Record<string, unknown>) : {}
  const out = emptyHdfcForm()
  for (const k of HDFC_FORM_KEYS) {
    out[k] = String(src[k] ?? '').slice(0, 4000)
  }
  // Legacy key aliases from earlier short form
  if (!out.fullAddress && src.address) out.fullAddress = String(src.address).slice(0, 4000)
  return out
}

