export function hdfcFormSummaryLines(form: Record<string, string>): string[] {
  const lines: string[] = []
  for (const k of HDFC_FORM_KEYS) {
    if (k === 'clientPickHint') continue
    const v = (form[k] || '').trim()
    if (!v) continue
    lines.push(`${HDFC_FORM_LABELS[k] || k}: ${v}`)
  }
  return lines
}
