export function liveI18nScript(): string {
  return `var LIVE_I18N=${JSON.stringify(LIVE_I18N)};
var CUR_LANG='en';
function t(k){
  var pack=LIVE_I18N[CUR_LANG]||LIVE_I18N.en;
  return (pack&&pack[k])||LIVE_I18N.en[k]||k;
}
function saveLang(id){
  CUR_LANG=LIVE_I18N[id]?id:'en';
  try{localStorage.setItem('live_lang',CUR_LANG);}catch(e){}
}
function loadLang(){
  try{var v=localStorage.getItem('live_lang'); if(v&&LIVE_I18N[v]) CUR_LANG=v;}catch(e){}
}
function applyLang(){
  document.documentElement.lang=CUR_LANG==='or'?'or':CUR_LANG;
  document.documentElement.setAttribute('data-live-lang',CUR_LANG);
  document.querySelectorAll('[data-i18n]').forEach(function(n){
    var k=n.getAttribute('data-i18n'); if(!k)return;
    var raw=t(k);
    if(n.getAttribute('data-i18n-placeholder')==='1'){n.setAttribute('placeholder',raw);return;}
    if(n.getAttribute('data-i18n-br')==='1'){n.innerHTML=raw.replace(/\\n/g,'<br>');return;}
    n.textContent=raw;
  });
  ['langPickGate','langPickHome'].forEach(function(id){
    var s=document.getElementById(id); if(s) s.value=CUR_LANG;
  });
  var ban=document.getElementById('banner');
  if(ban && ban.classList.contains('err')){
    var locTexts=Object.keys(LIVE_I18N).map(function(id){return LIVE_I18N[id].locOn;});
    if(locTexts.indexOf(ban.textContent)!==-1) ban.textContent=t('locOn');
  }
  if(typeof window.liveAfterLang==='function') window.liveAfterLang();
}
function bindLangPick(id){
  var s=document.getElementById(id); if(!s||s.getAttribute('data-on'))return;
  s.setAttribute('data-on','1');
  s.addEventListener('change',function(){saveLang(s.value);applyLang();});
}
loadLang();
`
}
