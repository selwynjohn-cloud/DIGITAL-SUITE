function read(rel) {
  return readFileSync(resolve(root, rel), 'utf8')
}
function fail(msg) {
  console.error('FAIL:', msg)
  failed = true
}
function ok(msg) {
  console.log('OK:', msg)
}
function must(file, needle, why) {
  if (!existsSync(resolve(root, file))) return fail(`missing ${file}`)
  if (!read(file).includes(needle)) fail(`${file} missing ${why}: ${needle}`)
  else ok(why)
}
function mustNot(file, needle, why) {
  if (read(file).includes(needle)) fail(`${file} must not have ${why}`)
  else ok(`no ${why}`)
}

